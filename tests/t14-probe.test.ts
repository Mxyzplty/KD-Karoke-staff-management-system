// T14 acceptance 1 (metadata, ground truth: F17 is C-gt because golden capture G-10 was never stored).
// Tolerances: duration ±1 ms or one frame step (container vs packet end), VFR average fps ±0.5 %, CFR fps exact,
// everything else exact. The average is frames / (last pts − first pts + last packet duration), from ffprobe's packet
// timestamps; ffprobe's own avg_frame_rate field divides by the track-header duration instead (S5a: 22.16 vs 21.67).
import { readdirSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { probeMedia, quickTimeCreation } from '../apps/web/src/media/probe';
import { mediaKind } from '../apps/web/src/media/files';
import { bytes, expectedFacts, ffmpegAvailable, hasStore, HEIC_SOURCE, media, MEDIA, STORE } from './media-fixtures';

async function check(file: string) {
  const name = path.basename(file), info = await probeMedia(new Blob([bytes(file)]), name, mediaKind(name)!), facts = expectedFacts(file);
  if (facts.image) { expect({ width: info.image!.width, height: info.image!.height }).toEqual(facts.image); return info; }
  if (facts.video) {
    const v = info.video!, step = 1000 / facts.video.fps;
    expect(Math.abs(info.durationMs! - facts.durationMs)).toBeLessThanOrEqual(Math.max(1, step));
    expect({ codec: v.codec, codedWidth: v.codedWidth, codedHeight: v.codedHeight, displayWidth: v.displayWidth, displayHeight: v.displayHeight, rotation: v.rotation, vfr: v.vfr, frameCount: v.frameCount,
      colour: { primaries: v.colour.primaries, transfer: v.colour.transfer, matrix: v.colour.matrix } })
      .toEqual({ codec: facts.video.codec, codedWidth: facts.video.codedWidth, codedHeight: facts.video.codedHeight, displayWidth: facts.video.displayWidth, displayHeight: facts.video.displayHeight,
        rotation: facts.video.rotation, vfr: facts.video.vfr, frameCount: facts.video.frameCount, colour: facts.video.colour });
    if (v.vfr) expect(Math.abs(v.fps / facts.video.fps - 1)).toBeLessThanOrEqual(0.005); else expect(v.fps).toBeCloseTo(facts.video.fps, 6);
    expect(v.hdr).toBe(v.colour.transfer === 'pq' ? 'pq' : v.colour.transfer === 'hlg' ? 'hlg' : v.colour.primaries === 'bt2020' ? 'bt2020' : null);
  }
  if (facts.audio) expect(info.audio).toEqual(facts.audio); else expect(info.audio).toBeNull();
  return info;
}
describe.skipIf(!ffmpegAvailable())('T14 probe of every media class generated by ffmpeg (CI)', () => {
  // mpeg4.avi needs the software probe (libav WASM), which runs only in a browser: the Chromium F7 test covers it.
  for (const name of [...Object.keys(MEDIA).filter(n => n !== 'mpeg4.avi'), 'rotation-90.mp4']) it(`${name} matches ffprobe`, async () => { await check(media(name)); });
  it('HEIC (single item and 2 × 2 grid) and SVG sizes come from the container / root element (review F8)', async () => {
    for (const [name, size] of [['pattern.heic', { width: HEIC_SOURCE.single.w, height: HEIC_SOURCE.single.h }], ['grid.heic', { width: HEIC_SOURCE.grid.w, height: HEIC_SOURCE.grid.h }], ['pattern.svg', { width: 96, height: 64 }]] as const) {
      const info = await probeMedia(new Blob([bytes(media(name))]), name, 'image');
      expect({ width: info.image!.width, height: info.image!.height }, name).toEqual(size);
    }
  });
  it('SAR 1216:1215 at 1080 × 1920 shows as 1081 × 1920 (G-08 decision 3)', async () => {
    const info = await check(media('sar-1216-1215.mp4'));
    expect(info.video).toMatchObject({ codedWidth: 1080, codedHeight: 1920, displayWidth: 1081, displayHeight: 1920 });
    // Mediabunny reports the ratio reduced to the square-pixel width (1081:1080); the same display width either way.
    expect(info.video!.sampleAspectRatio.num / info.video!.sampleAspectRatio.den).toBeCloseTo(1216 / 1215, 3);
  });
  it('HDR detection: PQ and HLG BT.2020 HEVC 10-bit; SDR HEVC 10-bit is not HDR', async () => {
    expect((await check(media('hevc10-pq.mp4'))).video).toMatchObject({ hdr: 'pq', bitDepth: 10, colour: { primaries: 'bt2020', transfer: 'pq', matrix: 'bt2020-ncl' } });
    expect((await check(media('hevc10-hlg.mp4'))).video).toMatchObject({ hdr: 'hlg', bitDepth: 10 });
    expect((await check(media('hevc10-sdr.mp4'))).video).toMatchObject({ hdr: null, bitDepth: 10, colour: { transfer: 'bt709' } });
  });
  it('capture date from the movie header; GPS from the MP4 loci box and the QuickTime ©xyz atom', async () => {
    const info = await check(media('h264-aac.mp4'));
    expect(info.capturedAt).toBe('2026-03-04T05:06:07.000Z'); expect(info.latitude).toBeCloseTo(52.37, 4); expect(info.longitude).toBeCloseTo(4.89, 4);
    const mov = await check(media('prores.mov'));
    expect(mov.latitude).toBeCloseTo(-33.8688, 4); expect(mov.longitude).toBeCloseTo(151.2093, 4);
    expect(await quickTimeCreation(new Blob([bytes(media('undated.mp4'))]))).toBeNull();
  });
  it('unrecognisable bytes → ingest form of UNSUPPORTED_INPUT; a recognised but truncated or damaged file → CORRUPT_FILE', async () => {
    await expect(probeMedia(new Blob([new Uint8Array(4096).fill(7)]), 'noise.mp4', 'video')).rejects.toMatchObject({ code: 'UNSUPPORTED_INPUT', category: 'system_error' });
    const whole = Buffer.from(bytes(media('h264-aac.mp4')));
    // ffmpeg writes the movie box at the end: cutting the file removes it.
    await expect(probeMedia(new Blob([whole.subarray(0, 600)]), 'cut.mp4', 'video')).rejects.toMatchObject({ code: 'CORRUPT_FILE', category: 'user_error', message: 'Corrupt or incomplete file — re-export and re-upload.' });
    const damaged = Buffer.from(whole), at = damaged.indexOf('mvhd'); damaged.writeUInt32BE(0, at + 4 + 4 + 8); // movie timescale = 0
    await expect(probeMedia(new Blob([damaged]), 'damaged.mp4', 'video')).rejects.toMatchObject({ code: 'CORRUPT_FILE' });
  });
});
describe.skipIf(!hasStore)('T14 probe of the fixture store (S1–S5i, corpus, amsterdam jpg; ground truth)', () => {
  const files = !hasStore ? [] : ['synthetic', 'corpus'].flatMap(dir => readdirSync(path.join(STORE, dir)).filter(n => mediaKind(n) && !n.endsWith('.txt')).map(n => path.join(STORE, dir, n)));
  for (const file of files) it(`${path.basename(file)} matches ffprobe`, async () => {
    const name = path.basename(file), info = await check(file);
    if (name === 'S5d-rotation-90.mp4') expect(info.video).toMatchObject({ displayWidth: 1080, displayHeight: 1920 });
    if (name === 'S5a-vfr.mp4') expect(info.video).toMatchObject({ vfr: true, frameCount: 65 });
    if (name.startsWith('S5b')) expect(info.video?.hdr).toBe('pq');
    if (name.startsWith('S5c')) expect(info.video?.hdr).toBe('hlg');
    if (name === 'amsterdam-houseboat-exif.jpg') {
      // Manifest: mjpeg 2736x3648; EXIF 2017-06-23 16:19:32; GPS 52.369630 N, 4.899883 E.
      expect(info.image).toEqual({ width: 2736, height: 3648, orientation: 1 });
      expect(info.capturedAt).toBe('2017-06-23T16:19:32.000Z'); expect(info.latitude).toBeCloseTo(52.36963, 5); expect(info.longitude).toBeCloseTo(4.899883, 5);
    }
  });
});
